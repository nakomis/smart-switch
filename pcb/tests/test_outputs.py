"""Petro's generated hand-offs: pins.h for the firmware and case-interface.json for the case
(PETRO-6), both from the same source as the board, so neither can drift from it."""
import json
import re

from board import petro_board as pb
from board.placement import bbox

C = pb.build_petro()
P = pb.place_petro(C)


def test_pins_h_defines_every_gpio_once():
    h = pb.pins_h()
    assert h.startswith("/* Generated by pcb/build.py") and "#pragma once" in h
    defs = dict(re.findall(r"#define PETRO_PIN_(\w+) (\d+)", h))
    assert {k: int(v) for k, v in defs.items()} == pb.GPIO


def test_pins_h_says_which_test_hole_carries_what():
    h = pb.pins_h()
    for ref, net in pb.TEST_HOLES.items():
        assert f"{ref} {net}" in h


def test_case_interface_matches_the_board():
    ci = json.loads(pb.case_interface(C, P))
    assert ci["board"] == {"width": pb.W, "height": pb.H, "thickness": 1.6, "origin": "top-left, y down"}
    assert {h["ref"]: (h["x"], h["y"]) for h in ci["holes"]} == pb.HOLES
    assert not any(h["plated"] for h in ci["holes"])          # rev B: no copper reaches a screw
    led = ci["led"]
    assert (led["x"], led["y"]) == pb.AT["D1"][:2]
    assert led["flange_ring"] == [round(v, 3) for v in pb.led_ring()]
    sw = ci["button"]
    assert (sw["x"], sw["y"]) == pb.AT["SW1"][:2]
    for ref in ("J1", "J2", "J3", "J4"):
        assert ci["connectors"][ref]["body"] == [round(v, 3) for v in bbox(P, ref)]
    assert ci["connectors"]["J1"]["edge"] == "left" and ci["connectors"]["J2"]["edge"] == "right"
    assert ci["connectors"]["J3"]["edge"] == "bottom"
    ax0, ay0, ax1, ay1 = ci["antenna_overhang"]
    assert ay0 == pb.H and ay1 > pb.H and ax1 - ax0 > 10


def test_case_interface_says_the_board_is_live_but_the_island():
    """Rev B is non-isolated: the case must treat every part of the board as mains bar the safe
    I/O island, whose J3 may be reached from outside; USB (J4) is internal only."""
    ci = json.loads(pb.case_interface(C, P))
    assert ci["mains_area"]["whole_board"] is True
    assert ci["mains_area"]["except"] == [round(v, 3) for v in (*pb.island_area()[0], *pb.island_area()[2])]
    assert ci["connectors"]["J4"]["internal_only"] is True
    j3 = ci["connectors"]["J3"]
    assert j3["internal_only"] is False and j3["safe"] is True and j3["edge"] == "bottom"
    assert ci["led"]["part"] == "SK6812-EC20"
    assert {"K1", "XF1", "XF2", "XF3", "RV1", "L1", "L2", "C1", "C2"} <= set(ci["tall_parts"])


def test_case_interface_has_the_c6_antenna():
    ci = json.loads(pb.case_interface(C, P))
    ux = pb.AT["U1"][0]
    assert ci["antenna_overhang"] == [ux - 9.0, pb.H, ux + 9.0, pb.H + 6.5]


def test_pins_h_has_the_safe_io_and_the_island_fault_pin():
    h = pb.pins_h()
    for k in ("SPI_SCLK", "SPI_MOSI", "SPI_MISO", "SPI_CS", "I2C_SDA", "I2C_SCL", "SAFE_IN", "SAFE_OUT", "ISO_FLT"):
        assert f"#define PETRO_PIN_{k} {pb.GPIO[k]}\n" in h, k
    assert "SELV" in h and "ESP32-C6" in h


def test_usb_faces_the_right_hand_edge_with_nothing_in_the_plugs_way():
    """J4 is a side-entry JST SH: its mouth is the side away from its signal pads. It faces the
    right-hand edge (the cable leaves through the case's end wall, beside J2), its front within
    0.5 mm of the edge, and no part lies between the mouth and the edge."""
    ci = json.loads(pb.case_interface(C, P))
    assert ci["connectors"]["J4"]["edge"] == "right"
    x0, y0, x1, y1 = bbox(P, "J4")
    assert pb.W - 0.5 <= x1 <= pb.W
    pads = [pb.pad_xy(C, P, "J4", n) for n in "12345"]
    assert all(px < (x0 + x1) / 2 for px, _ in pads)              # signal pads at the back (left)
    for ref in C.instances:
        if ref != "J4":
            bx0, by0, bx1, by1 = bbox(P, ref)
            assert not (bx1 > x1 - 0.01 and by0 < y1 and by1 > y0), ref


def test_mains_terminals_open_towards_their_edges():
    """The DG636's wire openings are on its footprint's +y side (the two small rectangles in its
    silk outline). J1's must face the left-hand edge and J2's the right, so the wires come in
    from the case's end walls, never across the board; each body stays on the board."""
    from board.placement import rotate
    for ref, want in (("J1", -1), ("J2", 1)):
        dx, dy = rotate(0.0, 1.0, pb.AT[ref][2])
        assert round(dx) == want and round(dy) == 0, ref
        x0, _, x1, _ = bbox(P, ref)
        assert 0 <= x0 and x1 <= pb.W, ref
        assert (x0 < 1.0) if want < 0 else (x1 > pb.W - 1.0), ref      # opening at the edge
