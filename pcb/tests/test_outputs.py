"""Petro's generated hand-offs: pins.h for the firmware and case-interface.json for the case
(PETRO-6), both from the same source as the board, so neither can drift from it."""
import json
import re

from board import petro_board as pb
from board.placement import bbox

C = pb.build_petro()
P = pb.place_petro(C)


def test_pins_h_defines_every_gpio_once():
    h = pb.pins_h()
    assert h.startswith("/* Generated by pcb/build.py") and "#pragma once" in h
    defs = dict(re.findall(r"#define PETRO_PIN_(\w+) (\d+)", h))
    assert {k: int(v) for k, v in defs.items()} == pb.GPIO


def test_pins_h_says_which_test_hole_carries_what():
    h = pb.pins_h()
    for ref, net in pb.TEST_HOLES.items():
        assert f"{ref} {net}" in h


def test_case_interface_matches_the_board():
    ci = json.loads(pb.case_interface(C, P))
    assert ci["board"] == {"width": pb.W, "height": pb.H, "thickness": 1.6, "origin": "top-left, y down"}
    assert {h["ref"]: (h["x"], h["y"]) for h in ci["holes"]} == pb.HOLES
    assert all(h["plated"] == (h["ref"] in ("H3", "H4")) for h in ci["holes"])
    led = ci["led"]
    assert (led["x"], led["y"]) == pb.AT["D1"][:2]
    assert led["flange_ring"] == [round(v, 3) for v in pb.led_ring()]
    sw = ci["button"]
    assert (sw["x"], sw["y"]) == pb.AT["SW1"][:2]
    for ref in ("J1", "J2", "J3", "J5"):
        assert ci["connectors"][ref]["body"] == [round(v, 3) for v in bbox(P, ref)]
    assert ci["connectors"]["J1"]["edge"] == "left" and ci["connectors"]["J2"]["edge"] == "right"
    assert ci["connectors"]["J3"]["edge"] == "bottom"
    ax0, ay0, ax1, ay1 = ci["antenna_overhang"]
    assert ay0 == pb.H and ay1 > pb.H and ax1 - ax0 > 10
