"""A readable net table of a circuit, for review: every net with its group and the part pins on it.

    ./.venv/bin/python -m board.nettable > ../docs/petro-netlist.md
"""
from board.petro_board import GROUPS, build_petro


def _pin_name(inst, pad):
    names = [n for n, pads in inst.part.pins.items() if pad in pads]
    name = names[0] if names else pad
    return name if name == pad else f"{name}"


def net_table(c, groups):
    order = ["LINE", "LIVE", "PSU", "SWNODE", "NEUTRAL", "LOAD", "DIV1", "DIV2", "DIV3", "DIV4", "low voltage"]
    rows = []
    for name, pads in c.nets.items():
        g = groups.get(name, "low voltage")
        pins = sorted({f"{r}.{_pin_name(c.instances[r], p)}" for r, p in pads},
                      key=lambda s: (s.rstrip("0123456789.").split(".")[0], s))
        rows.append((order.index(g), g, name, pins))
    rows.sort(key=lambda r: (r[0], r[2]))
    out = ["| Group | Net | Pins |", "|---|---|---|"]
    out += [f"| {g} | `{n}` | {', '.join(p)} |" for _, g, n, p in rows]
    parts = ["| Ref | Part | Value | LCSC |", "|---|---|---|---|"]
    for ref in sorted(c.instances, key=lambda r: (r.rstrip("0123456789"), int(r[len(r.rstrip('0123456789')):] or 0))):
        i = c.instances[ref]
        parts.append(f"| {ref} | {i.part.key} | {i.value} | {i.part.lcsc or '(board only)'} |")
    return "\n".join(out), "\n".join(parts)


def main():
    c = build_petro()
    nets, parts = net_table(c, GROUPS)
    print("# Petro netlist\n")
    print("<!-- Generated by pcb/board/nettable.py from board/petro_board.py. Do not edit. -->\n")
    print(f"{len(c.instances)} parts, {len(c.nets)} nets. Groups are the mains potential groups of "
          "`board/rules.py`; every other net is low voltage, tied to neutral at the shunt (GND), so at\n"
          "mains potential: nothing on it may leave the case.\n")
    print("## Nets\n")
    print(nets)
    print("\n## Parts\n")
    print(parts)


if __name__ == "__main__":
    main()
